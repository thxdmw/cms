-- 为把用户密码从 md5（32 位十六进制）迁移到 BCrypt 做准备。
--
-- BCrypt 生成的哈希是固定 60 个字符（形如 $2a$10$ + 22 位盐 + 31 位摘要），
-- 而 user.password 原本只有 varchar(50)，直接写入会被截断（非严格模式）
-- 或直接报错（严格模式），一旦截断用户将永久无法登录。
-- 这里扩到 100 以留出余量，便于将来调整算法或加算法前缀。
--
-- 说明：本次不修改 salt 列。BCrypt 自带随机盐、不再需要该字段，
-- 但存量用户在下次登录被透明升级前仍要靠它校验历史 md5 密文，
-- 因此 salt 必须保留；待全部用户完成升级后可另行评估是否清理。
ALTER TABLE `user` MODIFY COLUMN `password` VARCHAR(100) NOT NULL COMMENT '密码：BCrypt 哈希（历史数据为 md5 加盐哈希，登录时自动升级）';
